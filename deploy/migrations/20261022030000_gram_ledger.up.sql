-- idempotent: a database that already applied the original version of this
-- migration keeps the same schema, and this file is a no-op there.
-- Gram 本地账本：per-user 余额 + 交易流水 + 频道金库。镜像 0009 Stars 账本
-- 形状，但货币隔离：Gram 与 Stars、TON 余额互不相通。金额为整数 Gram，永不为负。
CREATE TABLE IF NOT EXISTS public.gram_balances (
    user_id bigint NOT NULL,
    balance bigint DEFAULT 0 NOT NULL,
    granted boolean DEFAULT false NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT gram_balances_pkey PRIMARY KEY (user_id),
    CONSTRAINT gram_balances_balance_nonneg CHECK ((balance >= 0))
);

-- 流水：amount 带符号（贷记 > 0 / 借记 < 0）；peer_* 为对手方（grant/topup 等无对手时为空）。
CREATE TABLE IF NOT EXISTS public.gram_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    peer_type text DEFAULT '' NOT NULL,
    peer_id bigint DEFAULT 0 NOT NULL,
    amount bigint NOT NULL,
    reason text DEFAULT 'adjust' NOT NULL,
    title text DEFAULT '' NOT NULL,
    description text DEFAULT '' NOT NULL,
    date integer DEFAULT 0 NOT NULL,
    CONSTRAINT gram_transactions_pkey PRIMARY KEY (id)
);

-- keyset 分页：WHERE user_id=$1 [AND id < cursor] ORDER BY id DESC LIMIT n。
CREATE INDEX IF NOT EXISTS gram_transactions_user_id_idx ON public.gram_transactions USING btree (user_id, id DESC);

CREATE TABLE IF NOT EXISTS public.channel_gram_balances (
    channel_id bigint PRIMARY KEY,
    balance bigint DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT channel_gram_balances_shape_check CHECK (channel_id>0 AND balance>=0)
);

CREATE TABLE IF NOT EXISTS public.channel_gram_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    actor_user_id bigint NOT NULL,
    amount bigint NOT NULL,
    reason text NOT NULL,
    peer_type text DEFAULT '' NOT NULL,
    peer_id bigint DEFAULT 0 NOT NULL,
    date integer NOT NULL,
    CONSTRAINT channel_gram_transactions_shape_check CHECK (
        channel_id>0 AND actor_user_id>0 AND amount<>0 AND date>0 AND
        ((peer_type='' AND peer_id=0) OR (peer_type IN ('user','channel') AND peer_id>0)))
);
CREATE INDEX IF NOT EXISTS channel_gram_transactions_channel_idx
    ON public.channel_gram_transactions(channel_id,id DESC);
