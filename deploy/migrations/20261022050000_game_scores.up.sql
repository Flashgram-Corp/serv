-- Game scores: per-user best scores for chat games and inline games.
-- Chat games key on (peer, message); inline games key on the Bot API inline
-- message triple. One row per (game, user) holds the best score; writers only
-- ever raise it (or force it), so ranking reads never block writers.
CREATE TABLE IF NOT EXISTS public.game_scores (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind text NOT NULL,
    peer_type text DEFAULT '' NOT NULL,
    peer_id bigint DEFAULT 0 NOT NULL,
    msg_id integer DEFAULT 0 NOT NULL,
    inline_dc_id integer DEFAULT 0 NOT NULL,
    inline_msg_id bigint DEFAULT 0 NOT NULL,
    inline_access_hash bigint DEFAULT 0 NOT NULL,
    user_id bigint NOT NULL,
    score integer DEFAULT 0 NOT NULL,
    updated_at integer DEFAULT 0 NOT NULL,
    CONSTRAINT game_scores_pkey PRIMARY KEY (id),
    CONSTRAINT game_scores_kind_check CHECK (kind IN ('chat', 'inline')),
    CONSTRAINT game_scores_chat_check CHECK (
        (kind = 'chat' AND peer_id > 0 AND msg_id > 0 AND inline_msg_id = 0) OR
        (kind = 'inline' AND peer_id = 0 AND msg_id = 0 AND inline_msg_id <> 0)),
    CONSTRAINT game_scores_score_check CHECK (score >= 0)
);

-- One best score per (game, user); the partial uniques make concurrent
-- first-writes serialize on the game key instead of deadlocking.
CREATE UNIQUE INDEX IF NOT EXISTS game_scores_chat_user_uniq
    ON public.game_scores(peer_type, peer_id, msg_id, user_id)
    WHERE kind = 'chat';
CREATE UNIQUE INDEX IF NOT EXISTS game_scores_inline_user_uniq
    ON public.game_scores(inline_dc_id, inline_msg_id, inline_access_hash, user_id)
    WHERE kind = 'inline';

-- Ranking reads: top scores per game, ties oldest-first.
CREATE INDEX IF NOT EXISTS game_scores_chat_rank_idx
    ON public.game_scores(peer_type, peer_id, msg_id, score DESC, updated_at ASC, user_id ASC)
    WHERE kind = 'chat';
CREATE INDEX IF NOT EXISTS game_scores_inline_rank_idx
    ON public.game_scores(inline_dc_id, inline_msg_id, inline_access_hash, score DESC, updated_at ASC, user_id ASC)
    WHERE kind = 'inline';
